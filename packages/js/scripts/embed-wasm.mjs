// Embeds calc.wasm into a JavaScript module as base64. The package loads the
// engine from it, so the same code path works in Node.js, Next.js (server and
// client bundles) and browsers: no file system, no fetch, no bundler setup.
//
// Usage: node scripts/embed-wasm.mjs <calc.wasm> <output.js>
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error('usage: node scripts/embed-wasm.mjs <calc.wasm> <output.js>');
  process.exit(2);
}

const wasm = readFileSync(input);
const sha256 = createHash('sha256').update(wasm).digest('hex');
writeFileSync(
  output,
  `// Generated by scripts/embed-wasm.mjs from calc.wasm. Do not edit.\n` +
    `export const wasmSha256 = '${sha256}';\n` +
    `export const wasmBase64 =\n  '${wasm.toString('base64')}';\n`,
);
